// component that ships in the app (web bundle + Android shell). Re-run after
// changing dependencies: node scripts/notices.mjs
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

const NM = "apps/web/node_modules";
const read = (p) => readFileSync(p, "utf8").trim();
function licenseFile(dir) {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n));
  return f ? read(join(dir, f)) : null;
}
